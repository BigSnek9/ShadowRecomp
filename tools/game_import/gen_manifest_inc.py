"""gupe8p.json (hashes of a clean USA disc) -> runtime/first_run_manifest.inc for the first-run import in shadow.exe.
Run after changing gupe8p.json:  python tools/game_import/gen_manifest_inc.py"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'runtime', 'first_run_manifest.inc')

m = json.load(open(os.path.join(HERE, 'gupe8p.json'), encoding='utf-8'))
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/game_import/gen_manifest_inc.py from gupe8p.json - do not edit.\n')
    f.write(f'// Size + SHA-1 of every file of a clean {m["game_id"]} rev {m["revision"]} disc (hashes only, no game data).\n')
    for path, (size, sha) in m['files'].items():
        f.write(f'{{"{path}", {size}ull, "{sha}"}},\n')
print(OUT, len(m['files']))
